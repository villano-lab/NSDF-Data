"""The library reference page (docs/library/index.html) must match the code in python/.

It is generated by tools/build_library_reference.py. If this test fails, rebuild the page:

    python tools/build_library_reference.py
"""
import importlib
import importlib.util
import inspect
import warnings
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]


def _load_builder():
    spec = importlib.util.spec_from_file_location("build_library_reference", REPO / "tools" / "build_library_reference.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_library_reference_is_up_to_date():
    builder = _load_builder()
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        page = builder.render()
    have = builder.OUT.read_text(encoding="utf-8").replace("\r\n", "\n")
    assert have == page, "docs/library/index.html is out of date: run  python tools/build_library_reference.py"


def test_every_function_appears_on_the_page():
    builder = _load_builder()
    page = builder.OUT.read_text(encoding="utf-8")
    missing = []
    for modname in builder.module_names():
        module = importlib.import_module(modname)
        for name, f in inspect.getmembers(module, inspect.isfunction):
            if not name.startswith("_") and f.__module__ == module.__name__ and f'id="{modname}.{name}"' not in page:
                missing.append(f"{modname}.{name}")
    assert not missing, f"not on the reference page (rebuild it): {missing}"
